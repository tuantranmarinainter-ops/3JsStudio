"""Write src/shared/Game/UiAssets.luau (uploaded icon and UI-kit image ids, with 9-slice margins).

    python art/tools/make_ui_assets.py

Reads art/uploads.json (keys like "icons/Icon_Coin.png", "ui/ui_panel.png") and art/out/ui/kit.json.
Only images whose uploaded hash matches the current file are written.
"""

import json
import os

from make_art import ART, ROOT, UPLOADS, load, sha1

KIT = os.path.join(ART, "out", "ui", "kit.json")
TARGET = os.path.join(ROOT, "src", "shared", "Game", "UiAssets.luau")


def camel(snake):
    words = snake.split("_")
    return "".join("Button" if w == "btn" else w[:1].upper() + w[1:] for w in words)


def main():
    uploads = load(UPLOADS, {})
    kit = load(KIT, {})
    icons, sliced, stale = {}, {}, []
    for key, record in sorted(uploads.items()):
        if "/" not in key:
            continue
        path = os.path.join(ART, "out", *key.split("/"))
        if not os.path.exists(path) or sha1(path) != record["sha1"]:
            stale.append(key)
            continue
        folder, file = key.split("/")
        name = file[:-4]
        if folder == "icons":
            icons[name.removeprefix("Icon_")] = record["id"]
        elif folder == "ui" and name in kit:
            sliced[camel(name.removeprefix("ui_"))] = (record["id"], kit[name])
    lines = [
        "--!strict",
        "-- Generated by art/tools/make_ui_assets.py from art/uploads.json and art/out/ui/kit.json. Do not edit.",
        "-- Kit images are 9-slice: `slice` is the corner size in pixels of the `size`-pixel source image.",
        "export type Sliced = { image: string, size: { number }, slice: number }",
        "",
        "local UiAssets = {",
        "\tIcons = {",
    ]
    lines += [f'\t\t{name} = "rbxassetid://{asset_id}",' for name, asset_id in sorted(icons.items())]
    lines += ["\t} :: { [string]: string },", "\tKit = {"]
    for name, (asset_id, info) in sorted(sliced.items()):
        w, h = info["size"]
        lines.append(f'\t\t{name} = {{ image = "rbxassetid://{asset_id}", size = {{ {w}, {h} }}, slice = {info["slice"]} }},')
    lines += ["\t} :: { [string]: Sliced },", "}", "", "return UiAssets", ""]
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"UiAssets.luau: {len(icons)} icons, {len(sliced)} kit images, {len(stale)} stale {stale}")


if __name__ == "__main__":
    main()
