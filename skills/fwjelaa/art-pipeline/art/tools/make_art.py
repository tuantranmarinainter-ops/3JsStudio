"""Write src/shared/Game/Art.luau from the Blender manifest and the upload record.

    python art/tools/make_art.py

art/out/manifest.json  - written by art/blender/build.py (sizes, offsets, materials per part)
art/uploads.json       - asset ids recorded by the upload step, keyed by file name, with the sha1 that was uploaded
Only assets whose every mesh and texture is uploaded (and unchanged since) are written.
"""

import hashlib
import json
import os

ART = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(ART)
MANIFEST = os.path.join(ART, "out", "manifest.json")
UPLOADS = os.path.join(ART, "uploads.json")
TARGET = os.path.join(ROOT, "src", "shared", "Game", "Art.luau")


def sha1(path):
    with open(path, "rb") as fh:
        return hashlib.sha1(fh.read()).hexdigest()


def mesh_file(name):
    return os.path.join(ART, "out", "meshes", f"{name}.luau")


def texture_file(name):
    return os.path.join(ART, "out", "textures", name)


def load(path, default):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def uploaded_id(uploads, key, path):
    record = uploads.get(key)
    if not record or not os.path.exists(path) or record.get("sha1") != sha1(path):
        return None
    return record["id"]


def pending(manifest, uploads):
    """Files that still need uploading: [(kind, key, path)]."""
    todo = []
    for entry in manifest.values():
        for part in entry["parts"]:
            if uploaded_id(uploads, part["mesh"], mesh_file(part["mesh"])) is None:
                todo.append(("mesh", part["mesh"], mesh_file(part["mesh"])))
            texture = part.get("texture")
            if texture and uploaded_id(uploads, texture, texture_file(texture)) is None:
                todo.append(("texture", texture, texture_file(texture)))
    return todo


def vec(values):
    return "{ " + ", ".join(f"{v:g}" for v in values) + " }"


def main():
    manifest = load(MANIFEST, {})
    uploads = load(UPLOADS, {})
    lines = [
        "--!strict",
        "-- Generated by art/tools/make_art.py from art/out/manifest.json and art/uploads.json. Do not edit.",
        "-- Sizes and offsets are { x, y, z } in studs; offset is the part's centre relative to the asset origin.",
        "export type Part = {",
        "\tname: string,",
        "\tmesh: number,",
        "\ttexture: number?,",
        "\tsize: { number },",
        "\toffset: { number },",
        "\tmaterial: string,",
        "\tcolor: { number }?,",
        "\ttransparency: number,",
        "\tcollide: boolean,",
        "}",
        "export type Asset = { collide: string, parts: { Part } }",
        "",
        "local Art: { [string]: Asset } = {",
    ]
    written, skipped = 0, []
    for name in sorted(manifest):
        entry = manifest[name]
        parts = []
        complete = True
        for part in entry["parts"]:
            mesh_id = uploaded_id(uploads, part["mesh"], mesh_file(part["mesh"]))
            texture = part.get("texture")
            texture_id = uploaded_id(uploads, texture, texture_file(texture)) if texture else None
            if mesh_id is None or (texture and texture_id is None):
                complete = False
                break
            fields = [
                f'name = "{part["name"]}"',
                f"mesh = {mesh_id}",
                f"texture = {texture_id}" if texture_id else None,
                f"size = {vec(part['size'])}",
                f"offset = {vec(part['offset'])}",
                f'material = "{part.get("material", "SmoothPlastic")}"',
                f"color = {vec(part['color'])}" if part.get("color") else None,
                f"transparency = {part.get('transparency', 0):g}",
                f"collide = {'true' if part.get('collide', True) else 'false'}",
            ]
            parts.append("\t\t\t{ " + ", ".join(f for f in fields if f) + " },")
        if not complete:
            skipped.append(name)
            continue
        lines.append(f"\t{name} = {{")
        lines.append(f'\t\tcollide = "{entry.get("collide", "Box")}",')
        lines.append("\t\tparts = {")
        lines.extend(parts)
        lines.append("\t\t},")
        lines.append("\t},")
        written += 1
    lines += ["}", "", "return Art", ""]
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"Art.luau: {written} assets written, {len(skipped)} waiting for upload {skipped}")


if __name__ == "__main__":
    main()
