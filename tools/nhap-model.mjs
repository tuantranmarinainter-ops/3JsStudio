async function timPolyhaven(q) {
  const ds = await polyhavenDS(); const ws = q.toLowerCase().split(/\s+/).filter(Boolean);
  const out = [];
  for (const [id, m] of Object.entries(ds)) {
    const hay = `${id} ${m.name} ${(m.tags || []).join(' ')} ${(m.categories || []).join(' ')}`.toLowerCase();
    if (ws.every((w) => hay.includes(w))) out.push(phThongTin(id, m));
  }
  return out;
}
async function taiPolyhaven(id, dir) {
  const f = await http(`${PH}/files/${encodeURIComponent(id)}`);
  const g = f.gltf?.['1k']?.gltf || f.gltf?.['2k']?.gltf;
  if (!g) throw new Error('Poly Haven không có gltf 1k/2k cho ' + id);
  const items = [[path.basename(new URL(g.url).pathname), g], ...Object.entries(g.include || {})];
  const tong = items.reduce((s, [, v]) => s + (v.size || 0), 0);
  if (tong > TOI_DA_TAI) throw new Error(`bản tải ${tong} byte > ${TOI_DA_TAI}`);
  let chinh = null;
  for (const [rel, v] of items) {
    const dich = path.resolve(dir, rel);
    if (!dich.startsWith(path.resolve(dir) + path.sep)) throw new Error('đường dẫn lạ: ' + rel);
    if (!/\.(gltf|bin|jpe?g|png|webp)$/i.test(dich)) throw new Error('loại tệp lạ: ' + rel);
    fs.mkdirSync(path.dirname(dich), { recursive: true });
    fs.writeFileSync(dich, await http(v.url, { bytes: true, max: TOI_DA_TAI }));
    if (/\.gltf$/i.test(dich)) chinh = dich;
  }
  return chinh;
}

