// ---------- giải nén zip tải về (dữ liệu không tin cậy) ----------
function giaiNenGltf(buf, dir) {
  const zip = path.join(dir, 'tai.zip'); fs.writeFileSync(zip, buf);
  const ds = spawnSync('tar', ['-tf', zip], { encoding: 'utf8' });
  if (ds.status !== 0) throw new Error('không đọc được zip: ' + che(ds.stderr));
  const ten = ds.stdout.split(/\r?\n/).filter(Boolean);
  for (const t of ten) {
    if (/(^|[\\/])\.\.([\\/]|$)|^[\\/]|^[a-zA-Z]:/.test(t)) throw new Error('zip có đường dẫn nguy hiểm: ' + t);
  }
  const ok = ten.filter((t) => /\.(gltf|glb|bin|jpe?g|png|webp)$/i.test(t) || t.endsWith('/'));
  const x = spawnSync('tar', ['-xf', zip, '-C', dir, ...ok], { encoding: 'utf8' });
  if (x.status !== 0) throw new Error('giải nén lỗi: ' + che(x.stderr));
  fs.rmSync(zip);
  const g = ten.find((t) => /\.gltf$/i.test(t)) || ten.find((t) => /\.glb$/i.test(t));
  if (!g) throw new Error('zip không có gltf/glb');
  return path.join(dir, g);
}

// ---------- manifest + ghi công ----------
export function ghiManifest(entry, file = MANIFEST) {
  let txt = fs.readFileSync(file, 'utf8');
  const arr = JSON.parse(txt);
  const kieu = JSON.stringify(arr, null, 1) === txt.trimEnd();
  const i = arr.findIndex((e) => e.id === entry.id);
  if (i >= 0 && !entry.id.startsWith('nhap/')) throw new Error('không ghi đè dòng manifest cũ ' + entry.id);
  if (kieu) {
    if (i >= 0) arr[i] = entry; else arr.push(entry);
    fs.writeFileSync(file, JSON.stringify(arr, null, 1) + (txt.endsWith('\n') ? '\n' : ''));
  } else {   // định dạng lạ: chỉ chèn chữ trước dấu ] cuối
    if (i >= 0) throw new Error('manifest không đúng định dạng chuẩn; không thể thay dòng cũ');
    const k = txt.lastIndexOf(']');
    const khoi = JSON.stringify(entry, null, 1).split('\n').map((l) => ' ' + l).join('\n');
    fs.writeFileSync(file, txt.slice(0, k).replace(/\s*$/, '') + ',\n' + khoi + '\n' + txt.slice(k));
  }
}
