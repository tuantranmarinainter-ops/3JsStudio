// ---------- HTTP ----------
async function http(url, { headers = {}, bytes = false, max = 0 } = {}) {
  const r = await fetch(url, { headers: { 'User-Agent': UA, ...headers }, redirect: 'follow', signal: AbortSignal.timeout(60000) });
  if (!r.ok) {
    const body = che((await r.text().catch(() => '')).slice(0, 300));
    const e = new Error(`HTTP ${r.status} ${new URL(url).host}${new URL(url).pathname}: ${body}`); e.status = r.status; throw e;
  }
  if (!bytes) return r.json();
  const len = Number(r.headers.get('content-length') || 0);
  if (max && len > max) throw new Error(`tệp ${len} byte vượt giới hạn ${max}`);
  const buf = Buffer.from(await r.arrayBuffer());
  if (max && buf.length > max) throw new Error(`tệp ${buf.length} byte vượt giới hạn ${max}`);
  return buf;
}

