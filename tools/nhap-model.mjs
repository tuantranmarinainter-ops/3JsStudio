export function ghiCredits(info, ten, file = CREDITS) {
  let lines = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').split(/\r?\n/) : [
    '# Model nhập từ mạng (assets/nhap/) — ghi công', '', 'CC BY: BẮT BUỘC ghi đủ tên model, tác giả, nguồn, giấy phép khi đăng video. Dán vào mô tả video / màn hình cuối.', ''];
  lines = lines.filter((l) => !l.startsWith(`- [nhap/${ten}]`) && l !== '');
  const dau = lines.filter((l) => !l.startsWith('- ')), muc = lines.filter((l) => l.startsWith('- '));
  muc.push(dongGhiCong(info, ten)); muc.sort();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, dau.join('\n') + '\n\n' + muc.join('\n') + '\n');
}

