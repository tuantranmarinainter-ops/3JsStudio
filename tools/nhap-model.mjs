export const NGUONG = JSON.parse(fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'nhap-nguong.json'), 'utf8'));
export const loaiHopLe = (l) => Object.hasOwn(NGUONG.loai, l);
// 'ly-tuong' | 'thap' (dưới khoảng lý tưởng, vẫn đạt) | 'chap-nhan' (trên lý tưởng, ≤ tối đa) | 'vuot' | 'chua-ro'
export function phanLoai(tris, loai) {
  const n = NGUONG.loai[loai]; if (!n) throw new Error('loại lạ: ' + loai);
  if (tris == null || !Number.isFinite(Number(tris))) return 'chua-ro';
  const t = Number(tris);
  if (t > n.toiDa) return 'vuot';
  if (t > n.lyTuong) return 'chap-nhan';
  return t < n.min ? 'thap' : 'ly-tuong';
}
const THU_TU = { 'ly-tuong': 0, thap: 1, 'chap-nhan': 2, 'chua-ro': 3, vuot: 4 };
export const sapXepUngVien = (ds, loai) => ds.map((m) => ({ ...m, hang: phanLoai(m.tamGiac, loai) }))
  .sort((a, b) => THU_TU[a.hang] - THU_TU[b.hang] || (a.hang === 'thap' ? b.tamGiac - a.tamGiac : (a.tamGiac ?? 0) - (b.tamGiac ?? 0)));
const loaiTuArgs = (a) => { const l = a.loai === undefined || a.loai === true ? NGUONG.mac_dinh : String(a.loai); if (!loaiHopLe(l)) loi(`--loai lạ: ${l} (có: ${Object.keys(NGUONG.loai).join(', ')})`); return l; };

