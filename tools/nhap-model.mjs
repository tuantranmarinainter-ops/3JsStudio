// ---------- giấy phép: chỉ CC0 và CC BY ----------
export function chuanGiayPhep(raw) {
  const s = String(raw || '').trim().toLowerCase();
  if (!s) return null;
  if (/(^|[^a-z])(nc|nd|sa)([^a-z]|$)|noncommercial|non-commercial|noderiv|sharealike|editorial|standard|all rights/.test(s.replace(/cc[ -]?by/g, 'ccby'))) return null;
  if (/^cc0|cc0 ?1|public domain|^0$|zero/.test(s)) return { ma: 'CC0', ten: 'CC0 1.0', url: 'https://creativecommons.org/publicdomain/zero/1.0/', cc0: true };
  const m = s.match(/^(?:cc[ -]?by|cc attribution|attribution)(?:[ -]?(\d\.\d))?$/);
  if (m) { const v = m[1] || '4.0'; return { ma: `CC BY ${v}`, ten: `CC-BY-${v}`, url: `http://creativecommons.org/licenses/by/${v}/`, cc0: false }; }
  return null;
}
export const giayPhepHopLe = (s) => /^CC0\b|^CC BY \d\.\d\b/.test(String(s || '').replace(/\s*\(mesh\)\s*$/, ''));
