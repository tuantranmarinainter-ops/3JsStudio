const SF = 'https://api.sketchfab.com/v3';
const sfHead = () => (ENV.SKETCHFAB_API_TOKEN ? { Authorization: `Token ${ENV.SKETCHFAB_API_TOKEN}` } : {});

export function sfThongTin(m) {
  const gp = chuanGiayPhep(m.license?.label || m.license?.slug);
  const tags = (m.tags || []).map((t) => t.name || t.slug).join(' ');
  return {
    nguon: 'sketchfab', id: m.uid, ten: m.name, tacGia: m.user?.displayName || m.user?.username || '?',
    tacGiaUrl: m.user?.profileUrl || '', gp, gpRaw: m.license?.label, tamGiac: m.faceCount ?? null,
    url: m.viewerUrl?.replace('/none-', '/' + String(m.name || 'model').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') + '-') || `https://sketchfab.com/3d-models/${m.uid}`,
    ai: coAI(`${m.name} ${tags} ${m.description || ''}`),
    kb: m.archives?.glb?.size ?? m.archives?.gltf?.size ?? null,
  };
}
async function timSketchfab(q, toiDa) {
  const out = [];
  for (const lic of ['cc0', 'by']) {
    const u = `${SF}/search?type=models&q=${encodeURIComponent(q)}&downloadable=true&license=${lic}&count=24&sort_by=-likeCount`;
    const j = await http(u, { headers: sfHead() });
    for (const m of j.results || []) out.push(sfThongTin(m));
  }
  return out;
}
async function layDuLieuSketchfab(id) {
  const m = await http(`${SF}/models/${id}`, { headers: sfHead() });
  return sfThongTin(m);
}
async function taiSketchfab(id, dir) {
  const d = await http(`${SF}/models/${id}/download`, { headers: sfHead() });
  const pick = d.glb?.url ? ['glb', d.glb] : d.gltf?.url ? ['gltf', d.gltf] : null;
  if (!pick) throw new Error('Download API không trả glb/gltf');
  if (pick[1].size && pick[1].size > TOI_DA_TAI) throw new Error(`bản tải ${pick[1].size} byte > ${TOI_DA_TAI}`);
  const buf = await http(pick[1].url, { bytes: true, max: TOI_DA_TAI });     // URL ký sẵn (S3): không gửi token sang host khác
  if (pick[0] === 'glb') { const f = path.join(dir, 'model.glb'); fs.writeFileSync(f, buf); return f; }
  return giaiNenGltf(buf, dir);
}

